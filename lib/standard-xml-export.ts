import "server-only"
import { z } from "zod"
import { TRPCError } from "@trpc/server"
import { getCommunityStandard } from "./community-standard"
import { contributionFingerprint } from "./contribution-guard"
import { standardXmlTemplate, XmlTemplateError } from "./standard-xml-template"

export const standardXmlExportSchema = z
  .object({
    vocabularySlug: z
      .string()
      .regex(/^[a-z0-9][a-z0-9_-]*$/)
      .max(200),
    mode: z.enum(["reference", "working", "release"]),
    referenceReleaseId: z
      .string()
      .min(1)
      .max(500)
      .regex(/^[a-zA-Z0-9_.:-]+$/)
      .optional(),
    releaseId: z.string().uuid().optional(),
    profile: z
      .string()
      .regex(/^[a-z][a-z0-9_-]*$/)
      .max(100),
    expectedFingerprint: z
      .string()
      .regex(/^[a-f0-9]{64}$/)
      .optional()
  })
  .strict()
  .superRefine((value, ctx) => {
    if ((value.mode === "release") !== Boolean(value.releaseId))
      ctx.addIssue({
        code: "custom",
        message: "Select a community release only in release mode."
      })
    if (value.mode === "reference" && !value.referenceReleaseId)
      ctx.addIssue({ code: "custom", message: "Select a reference version." })
  })

type Reader = Parameters<typeof getCommunityStandard>[0]

export async function exportStandardXml(
  reader: Reader,
  input: z.infer<typeof standardXmlExportSchema>,
  viewerId: number | null
) {
  // The same live content and source grants as Standard, before reading any export data.
  const data = await getCommunityStandard(reader, input, viewerId)
  if (data.reference && input.mode !== "release" && !input.referenceReleaseId)
    throw new TRPCError({
      code: "BAD_REQUEST",
      message: "Select a reference version before exporting."
    })
  if (
    input.profile !== "community" &&
    !data.profiles.some((row) => row.id === input.profile)
  )
    throw new TRPCError({
      code: "NOT_FOUND",
      message: "This section is unavailable."
    })
  if (
    input.mode === "working" &&
    input.expectedFingerprint &&
    input.expectedFingerprint !== data.fingerprint
  )
    throw new TRPCError({
      code: "CONFLICT",
      message:
        "The working version changed. Reload Standard before downloading."
    })
  const entries =
    input.mode === "reference"
      ? data.referenceEntries
      : input.mode === "release"
        ? data.selectedRelease!.snapshot.entries
        : data.working.entries
  const selected = entries.filter(
    (entry) => (entry.profileKey ?? "community") === input.profile
  )
  const profile = data.profiles.find((row) => row.id === input.profile)
  const fingerprint = contributionFingerprint(selected)
  const header = [
    "Generated by MatSci-SAM. XML template format 1.",
    `Vocabulary: ${input.vocabularySlug}. Section: ${input.profile}.`,
    input.mode === "reference"
      ? `Reference: ${data.reference!.id}.`
      : input.mode === "release"
        ? `Community release: ${data.selectedRelease!.name}. Release ID: ${data.selectedRelease!.id}.`
        : "Community working version with accepted changes only.",
    ...(input.mode !== "reference"
      ? ["Community changes do not imply approval by the reference publisher."]
      : []),
    ...(data.reference
      ? [
          `Reference version: ${data.reference.version}. Source: ${data.reference.source.sourceUrl}.`,
          `Attribution: ${data.reference.source.attribution}`,
          `Source SHA-256: ${data.reference.source.sha256}`
        ]
      : []),
    `Exported section SHA-256: ${fingerprint}`,
    `Section only. Inherited sections are not included${profile?.inherits.length ? `: ${profile.inherits.join(", ")}` : ""}.`,
    ...(profile?.methodSelectionRequired
      ? ["This section also requires a selected method profile."]
      : [])
  ]
  try {
    const xml = standardXmlTemplate(selected, header)
    const version =
      input.mode === "release"
        ? data.selectedRelease!.id
        : (data.reference?.version ?? "community")
    const safeVersion = version.replace(/[^A-Za-z0-9_-]/g, "-").slice(0, 60)
    return {
      xml,
      filename: `${input.vocabularySlug.slice(0, 80)}-${safeVersion}-${input.mode}-${input.profile.slice(0, 50)}-template.xml`
    }
  } catch (error) {
    if (error instanceof XmlTemplateError)
      throw new TRPCError({ code: "BAD_REQUEST", message: error.message })
    throw error
  }
}

/** Shared by the route and integration tests, including headers on every failure. */
export async function standardXmlResponse(
  reader: Reader,
  request: Request,
  viewerId: number | null
) {
  const headers = {
    "Cache-Control": "private, no-store",
    Vary: "Cookie",
    "X-Content-Type-Options": "nosniff"
  }
  const params = new URL(request.url).searchParams
  const parsed = standardXmlExportSchema.safeParse(Object.fromEntries(params))
  if (
    !parsed.success ||
    [...params.keys()].some((key) => params.getAll(key).length !== 1)
  )
    return new Response("Choose a version and section to export.", {
      status: 400,
      headers
    })
  try {
    const document = await exportStandardXml(reader, parsed.data, viewerId)
    return new Response(document.xml, {
      headers: {
        ...headers,
        "Content-Type": "application/xml; charset=utf-8",
        "Content-Disposition": `attachment; filename="${document.filename}"`
      }
    })
  } catch (error) {
    if (
      error instanceof TRPCError &&
      ["NOT_FOUND", "CONFLICT", "FORBIDDEN", "BAD_REQUEST"].includes(error.code)
    ) {
      const status =
        error.code === "NOT_FOUND"
          ? 404
          : error.code === "CONFLICT"
            ? 409
            : error.code === "FORBIDDEN"
              ? 403
              : 400
      return new Response(error.message, { status, headers })
    }
    console.error("Standard XML export failed", error)
    return new Response(
      "The template could not be generated. Please try again.",
      { status: 500, headers }
    )
  }
}
